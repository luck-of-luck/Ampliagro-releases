@register.filter
def grupo_label(grupo):
    return GRUPO_LABELS.get(_norm(grupo), str(grupo).title())


@register.filter
def grupo_icon(grupo):
    """Retorna o SVG de linha do grupo de cultura (um ícone por tipo de cultura),
    com fallback para um ícone genérico."""
    item = GRUPO_ICONES.get(_norm(grupo), GRUPO_ICONES["_default"])
    if isinstance(item, tuple):
        path, viewBox, fill, stroke, strokeWidth = item
    else:
        path = item
        viewBox = "0 0 24 24"
        fill = "none"
        stroke = "currentColor"
        strokeWidth = "1.7"

    return _icon_svg(path, viewBox, fill, stroke, strokeWidth)


